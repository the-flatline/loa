def draw(fb, text, x0, y0, size=8, on=True):
    """Draw Amiga text at pixel origin; returns width consumed."""
    gs = GLYPHS[size]
    cx = x0
    for ch in str(text).upper():
        g = gs.get(ch, gs[" "])
        for r, mask in enumerate(g["r"]):
            if mask == 0:
                continue
            for b in range(len(bin(mask)) - 2):
                if mask & (1 << b):
                    fb.px(cx + b, y0 + r, on)
        cx += g["w"] + 1
    return cx - x0


def width(text, size=8):
    """Pixel width of text at 1px letter spacing."""
    gs = GLYPHS[size]
    return sum(gs.get(ch, gs[" "])["w"] + 1 for ch in str(text).upper())

