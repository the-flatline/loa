def draw(fb, text, x0, y0):
    """Draw Topaz text at pixel origin; returns width consumed."""
    cx = x0
    for ch in str(text).upper():
        g = GLYPHS.get(ch, GLYPHS[" "])
        w = g["w"]
        for r in range(16):
            val = g["r"][r]
            for b in range(w):
                if val & (1 << b):
                    fb.px(cx + b, y0 + r)
        cx += w + 1                     # 1px letter spacing
    return cx - x0


def strip(text):
    """Build a marquee strip as 16 boolean rows (1px spacing included)."""
    rows = [[] for _ in range(16)]
    for ch in str(text).upper():
        g = GLYPHS.get(ch, GLYPHS[" "])
        w = g["w"]
        for r in range(16):
            val = g["r"][r]
            rows[r] += [1 if (val & (1 << b)) else 0 for b in range(w)]
            rows[r] += [0]
    return rows
